    def evaluate(self, game):
        score = 0

        score += self.material(game)

        return score

    def material(self, game):
        score = 0

        score += game.white_pawns.bit_count() * 100
        score -= game.black_pawns.bit_count() * 100

        score += game.white_knights.bit_count() * 320
        score -= game.black_knights.bit_count() * 320

        score += game.white_bishops.bit_count() * 330
        score -= game.black_bishops.bit_count() * 330

        score += game.white_rooks.bit_count() * 500
        score -= game.black_rooks.bit_count() * 500

        score += game.white_queens.bit_count() * 900
        score -= game.black_queens.bit_count() * 900

        return score

    def piece_square(self, game):
        score = 0

        piece_map = {
            "white_pawns": "P",
            "white_knights": "N",
            "white_bishops": "B",
            "white_rooks": "R",
            "white_queens": "Q",
            "white_kings": "K",

            "black_pawns": "p",
            "black_knights": "n",
            "black_bishops": "b",
            "black_rooks": "r",
            "black_queens": "q",
            "black_kings": "k",
        }

        for rank in range(1, 9):
            for file in range(1, 9):

                piece = game.getPiece(rank, file)

                if piece is None:
                    continue

                row = 8 - rank
                col = file - 1

                score += self.piece_square_tables[piece_map[piece]][row][col]

        return score